"""内容指纹：用来**冻结**某个模块，防止它被无意改动。

为什么单独抽成一个模块（而不是写在用例里）：

  1. **它必须能被单独测试** —— 尤其是"与平台换行无关"这件事（见下）；
  2. 用例里只剩一句"指纹必须等于这个值"，改动理由写在 `tests/test_agents.py`
     的 docstring 里（那是变更日志）。

================================================================================
⚠️ 为什么必须先把 CRLF 归一化成 LF 再算哈希（harness-log #42）
================================================================================

第一版是 `sha256(path.read_bytes())` —— 直接对**字节**取哈希。后果：

  本仓库的 `.gitattributes` 规定 `* text=auto eol=lf`，所以**克隆出来的文件是 LF**；
  而作者的 Windows 工作副本是 **CRLF**。同一个文件，两种字节 ⇒ 两个指纹。

于是这条"冻结"用例在**每一个干净克隆里都是红的**：

      expected: ba2fe0cb321bb615
      actual  : 5a5e5f1978330d11

它真正要守的是「**内容**有没有被改」，不是「换行符是哪个平台的」。
一个在干净克隆里必红的守卫，和一个永远绿的守卫，结果是一样的：**没人再信它**。

（顺带说明为什么 `.gitattributes` 不能解决这件事：它管的是**入库/检出**的字节，
  而 `read_bytes()` 读的是**磁盘上此刻的字节** —— 生成器/编辑器随时可能写出 CRLF，
  这正是 #39 的现场。）
"""

from __future__ import annotations

import hashlib
from pathlib import Path


def fingerprint(path: Path) -> str:
    """模块内容的指纹（16 位十六进制）——**与平台换行无关**。

    只归一化换行，别的字节一律照旧：改内容必须让指纹变化，否则这个守卫就没用了。
    """
    raw = path.read_bytes()
    return hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()[:16]
